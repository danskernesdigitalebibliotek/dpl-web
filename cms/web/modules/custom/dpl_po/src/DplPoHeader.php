<?php

declare(strict_types=1);

namespace Drupal\dpl_po;

use Drupal\Component\Gettext\PoHeader;

/**
 * Our own .po file header generator.
 *
 * Override cores .po file header to avoid date and other headers we don't
 * need. The date headers makes the files change on every run, even if no
 * translations has changed.
 */
class DplPoHeader extends PoHeader {

  /**
   * The plural formula of each language we generate files for.
   */
  protected const PLURAL_FORMS = [
    'da' => 'nplurals=2; plural=(n != 1);',
  ];

  /**
   * Class constructor.
   *
   * @param string $langcode
   *   The language the file is a translation into.
   */
  public function __construct(string $langcode) {
    if (!isset(self::PLURAL_FORMS[$langcode])) {
      throw new \InvalidArgumentException(sprintf('No plural formula is known for the language "%s".', $langcode));
    }

    parent::__construct($langcode);
    $this->pluralForms = self::PLURAL_FORMS[$langcode];
  }

  /**
   * {@inheritdoc}
   */
  public function __toString(): string {
    // The revision date carries gettext's placeholder for "not set" rather
    // than being left out. Some tools don't like it missing.
    return "# Generated by dpl_po. Do not edit by hand.\n"
      . "msgid \"\"\n"
      . "msgstr \"\"\n"
      . "\"Project-Id-Version: DPL CMS\\n\"\n"
      . "\"PO-Revision-Date: YEAR-MO-DA HO:MI+ZONE\\n\"\n"
      . "\"MIME-Version: 1.0\\n\"\n"
      . "\"Content-Type: text/plain; charset=utf-8\\n\"\n"
      . "\"Content-Transfer-Encoding: 8bit\\n\"\n"
      . "\"Language: " . $this->langcode . "\\n\"\n"
      . "\"Plural-Forms: " . $this->pluralForms . "\\n\"\n"
      . "\n";
  }

}
